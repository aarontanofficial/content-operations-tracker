create table if not exists public.batch_plans (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan_date date not null,
  plan_data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  constraint batch_plans_user_date_unique unique (user_id, plan_date)
);

alter table public.batch_plans enable row level security;

drop policy if exists "Users can read their own batch plans" on public.batch_plans;
create policy "Users can read their own batch plans"
  on public.batch_plans for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own batch plans" on public.batch_plans;
create policy "Users can insert their own batch plans"
  on public.batch_plans for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users can update their own batch plans" on public.batch_plans;
create policy "Users can update their own batch plans"
  on public.batch_plans for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

grant select, insert, update on public.batch_plans to authenticated;
grant usage, select on sequence public.batch_plans_id_seq to authenticated;
